import { expect, test, type Page } from '@playwright/test'

const trigger = (page: Page) => page.getByRole('button', { name: 'Multiplayer', exact: true })
const create = (page: Page) => page.getByRole('menuitem', { name: 'Create a Lobby', exact: true })
const join = (page: Page) => page.getByRole('menuitem', { name: 'Join a Lobby', exact: true })

test('click opens a compact menu without navigating, toggles and dismisses outside even within the header', async ({ page }) => {
  await page.goto('/')
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await trigger(page).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('menu', { name: 'Multiplayer' })).toBeVisible()
  await expect(create(page)).toHaveAttribute('href', '/multiplayer/create')
  await expect(join(page)).toHaveAttribute('href', '/multiplayer/join')
  await expect(create(page)).toHaveAccessibleDescription('Start a new game with friends.')
  await expect(join(page)).toHaveAccessibleDescription('Enter an existing lobby using a code.')
  await trigger(page).click()
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await trigger(page).click()
  await page.locator('main').click({ position: { x: 5, y: 300 } })
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await trigger(page).click()
  // A blank part of the header is outside this dropdown.
  await page.locator('.th-header').click({ position: { x: 5, y: 5 } })
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('menuitem')).toHaveCount(0)
})

test('keyboard supports arrows, wrapping, Home/End, typeahead, Enter/Space, Tab and Escape focus return', async ({ page }) => {
  await page.goto('/')
  await trigger(page).focus()
  await page.keyboard.press('Enter')
  await expect(create(page)).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(join(page)).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(create(page)).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(join(page)).toBeFocused()
  await page.keyboard.press('Home')
  await expect(create(page)).toBeFocused()
  await page.keyboard.press('End')
  await expect(join(page)).toBeFocused()
  await page.keyboard.press('c')
  await expect(create(page)).toBeFocused()
  await page.keyboard.press('j')
  await expect(join(page)).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger(page)).toBeFocused()
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('ArrowUp')
  await expect(join(page)).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(trigger(page)).toBeFocused()
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Space')
  await expect(create(page)).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('link', { name: 'How to play', exact: true }).filter({ visible: true })).toBeFocused()
  await trigger(page).focus()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/multiplayer\/create$/)
  await expect(page.getByRole('form', { name: 'Create a lobby' })).toBeVisible()
  await trigger(page).focus()
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('Space')
  await expect(page).toHaveURL(/\/multiplayer\/join$/)
  await expect(page.getByLabel('Lobby code')).toBeVisible()
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
  await page.goBack()
  await expect(page).toHaveURL(/\/multiplayer\/create$/)
  await expect(trigger(page)).toHaveAttribute('aria-expanded', 'false')
})

test('old entry URLs redirect to a working form and form deep links reload correctly', async ({ page }) => {
  for (const url of ['/multiplayer', '/lobby']) {
    await page.goto(url)
    await expect(page).toHaveURL(/\/multiplayer\/create$/)
    await expect(page.getByRole('form', { name: 'Create a lobby' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Multiplayer', exact: true })).toHaveCount(0)
  }
  await page.goto('/multiplayer/join')
  await page.reload()
  await expect(page.getByLabel('Lobby code')).toBeVisible()
  await expect(page.getByRole('group', { name: 'Difficulty' })).toHaveCount(0)
  await expect(trigger(page)).toHaveAttribute('aria-current', 'page')
})

for (const width of [320, 390, 768, 1200, 1280, 1440, 1920]) {
  test(`dropdown stays within the viewport and closes its mobile parent at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    const mobile = width <= 1200
    if (mobile) await page.getByRole('button', { name: 'Open navigation' }).click()
    await trigger(page).click()
    await expect(create(page)).toBeInViewport()
    await expect(join(page)).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    const box = (await page.getByRole('menu').boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(width)
    await page.screenshot({ path: `test-results/multiplayer-dropdown/${width}.png` })
    await page.keyboard.press('Escape')
    await expect(trigger(page)).toBeFocused()
    if (mobile) {
      await expect(page.getByRole('button', { name: 'Close navigation' })).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('button', { name: 'Open navigation' })).toBeFocused()
      await page.getByRole('button', { name: 'Open navigation' }).click()
    }
    await trigger(page).click()
    await join(page).click()
    await expect(page).toHaveURL(/\/multiplayer\/join$/)
    await expect(page.getByRole('heading', { name: 'Join a lobby' })).toBeVisible()
    if (mobile) await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeHidden()
  })
}

test('touch navigation selects both forms and reduced motion disables the transition', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  try {
    const page = await context.newPage()
    await page.goto('/')
    for (const mode of ['Create', 'Join']) {
      await page.getByRole('button', { name: 'Open navigation' }).tap()
      await trigger(page).tap()
      await page.getByRole('menuitem', { name: `${mode} a Lobby`, exact: true }).tap()
      await expect(page.getByRole('heading', { name: `${mode} a lobby`, exact: true })).toBeVisible()
    }
    await page.getByRole('button', { name: 'Open navigation' }).tap()
    await trigger(page).tap()
    const durations = await page.getByRole('menu').evaluate(el => getComputedStyle(el).transitionDuration)
    expect(durations.split(',').every(duration => parseFloat(duration) < 0.001)).toBe(true)
  } finally {
    await context.close()
  }
})
